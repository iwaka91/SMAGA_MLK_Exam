-- SMAGA Maliku Exam Core V0.6
-- Jalankan satu kali di Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.exams (
  id text primary key,
  code text not null unique,
  title text not null,
  description text not null default '',
  token text not null,
  token_backup1 text not null default '',
  token_backup2 text not null default '',
  duration_seconds integer not null check (duration_seconds > 0),
  status text not null default 'draft' check (status in ('draft','published')),
  leaderboard boolean not null default false,
  show_result_to_student boolean not null default true,
  shuffle_questions boolean not null default false,
  scoring_mode text not null default 'equal' check (scoring_mode in ('equal','custom')),
  classes jsonb not null default '[]'::jsonb,
  start_at timestamptz,
  end_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.questions (
  exam_id text not null references public.exams(id) on delete cascade,
  id text not null,
  position integer not null,
  kind text not null check (kind in ('pg','pgk')),
  type text not null,
  weight integer not null default 1,
  domain text not null default 'Umum',
  label text not null default '',
  stimulus text not null default '',
  question text not null,
  options jsonb not null default '[]'::jsonb,
  option_ids jsonb not null default '[]'::jsonb,
  shuffle_options boolean not null default false,
  image_url text not null default '',
  notes text not null default '',
  visual boolean not null default false,
  primary key (exam_id,id)
);

-- Kunci dipisahkan dari tabel soal. Browser siswa tidak pernah menerima tabel ini.
create table if not exists public.question_keys (
  exam_id text not null,
  question_id text not null,
  kind text not null check (kind in ('pg','pgk')),
  answer jsonb not null,
  weight integer not null default 1,
  primary key (exam_id,question_id),
  foreign key (exam_id,question_id) references public.questions(exam_id,id) on delete cascade
);

create table if not exists public.exam_sessions (
  session_id text primary key,
  exam_id text not null references public.exams(id) on delete cascade,
  participant_number text not null,
  name text not null,
  class_name text not null,
  login_at timestamptz not null,
  start_at timestamptz not null,
  end_at timestamptz not null,
  login_window text not null default '',
  submitted boolean not null default false
);
create index if not exists idx_exam_sessions_exam on public.exam_sessions(exam_id);
create index if not exists idx_exam_sessions_participant on public.exam_sessions(exam_id,participant_number);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  exam_id text not null references public.exams(id) on delete cascade,
  session_id text not null references public.exam_sessions(session_id) on delete cascade,
  idempotency_key text not null,
  participant_number text not null,
  name text not null,
  class_name text not null,
  score_raw numeric not null,
  max_raw numeric not null,
  score_100 numeric not null,
  correct_items integer not null default 0,
  question_count integer not null default 0,
  detail jsonb not null default '[]'::jsonb,
  submitted_at timestamptz not null default now(),
  accepted boolean not null default true,
  idempotent_replay boolean not null default false,
  show_result_to_student boolean not null default true,
  unique(session_id,idempotency_key)
);
create index if not exists idx_submissions_exam on public.submissions(exam_id);

create table if not exists public.assets (
  id text primary key,
  exam_id text null references public.exams(id) on delete set null,
  storage_path text not null unique,
  public_url text not null unique,
  mime text not null,
  size_bytes bigint not null default 0,
  source text not null default 'upload',
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  last_used_at timestamptz not null default now(),
  deleted_at timestamptz null
);
create index if not exists idx_assets_exam on public.assets(exam_id);
create index if not exists idx_assets_cleanup on public.assets(archived,deleted_at,created_at);

-- Server Core memakai service-role key. Anon/client tidak diberi akses langsung ke tabel inti.
alter table public.exams enable row level security;
alter table public.questions enable row level security;
alter table public.question_keys enable row level security;
alter table public.exam_sessions enable row level security;
alter table public.submissions enable row level security;
alter table public.assets enable row level security;

